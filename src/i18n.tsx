type LanguageContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  translate: (source: string) => string;
  suggestedLocale: Locale | null;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function detectPreferredLocale(): Locale | null {
  const candidates = navigator.languages?.length
    ? navigator.languages
    : [navigator.language];

  for (const candidate of candidates) {
    const code = candidate.toLowerCase().split("-")[0] as Locale;
    if (languageOptions.some((language) => language.code === code)) {
      return code;
    }
  }

  return null;
}

function readStoredLocale(): Locale {
  try {
    const hasManualPreference =
      window.localStorage.getItem(MANUAL_STORAGE_KEY) === "true";
    const stored = window.localStorage.getItem(STORAGE_KEY) as Locale | null;

    if (
      hasManualPreference &&
      languageOptions.some((language) => language.code === stored)
    ) {
      return stored as Locale;
    }
  } catch {
    // Browsers with storage disabled still use the browser-language preference.
  }

  return detectPreferredLocale() ?? "en";
}

function readSuggestedLocale(): Locale | null {
  return detectPreferredLocale();
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readStoredLocale);
  const suggestedLocale = useMemo(() => readSuggestedLocale(), []);

  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale);
    try {
      window.localStorage.setItem(MANUAL_STORAGE_KEY, "true");
      window.localStorage.setItem(STORAGE_KEY, nextLocale);
    } catch {
      // The current session can still switch languages without storage.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // Keep the in-memory selection even when storage is unavailable.
    }
  }, [locale]);

  const value = useMemo<LanguageContextValue>(
    () => ({
      locale,
      setLocale,
      translate(source: string) {
        if (locale === "en") return source;
        return translations[locale][source] ?? source;
      },
      suggestedLocale,
    }),
    [locale, setLocale, suggestedLocale],
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }
  return context;
}
